#!/usr/bin/env python3
"""Regenerate English Polly narration and an original, deterministic ambient bed.

This explicit command calls the paid Polly API using the caller's AWS credentials.
No cloud call is made by previewing, rendering, testing or hydrating existing media.
"""

from array import array
import hashlib
import json
import math
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import wave
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent


def probe(path):
    result = subprocess.check_output([
        "ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "json", str(path)], text=True)
    return float(json.loads(result)["format"]["duration"])


def main():
    for command in ("aws", "ffmpeg", "ffprobe"):
        if not shutil.which(command):
            raise SystemExit("Missing required executable: " + command)
    script = json.loads((ROOT / "narration.json").read_text())
    public = ROOT / "public"
    public.mkdir(exist_ok=True)
    clips = []
    with tempfile.TemporaryDirectory(prefix="ccdash-polly-") as scratch:
        scratch = Path(scratch)
        for scene in script["scenes"]:
            ssml = scratch / "speech.ssml"
            ssml.write_text('<speak><prosody rate="' + script["speech_rate"] + '">'
                            + escape(scene["text"]) + '</prosody></speak>')
            raw = scratch / "raw.mp3"
            subprocess.run([
                "aws", "polly", "synthesize-speech", "--region", script["region"],
                "--engine", script["engine"], "--voice-id", script["voice"],
                "--text-type", "ssml", "--text", "file://" + str(ssml),
                "--sample-rate", str(script["sample_rate"]), "--output-format", "mp3",
                "--query", "ContentType", "--output", "text", "--no-cli-pager",
                str(raw)], check=True, stdout=subprocess.DEVNULL)
            target = public / (scene["id"] + ".mp3")
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(raw),
                            "-af", "loudnorm=I=-18:TP=-2:LRA=7",
                            "-ar", str(script["sample_rate"]), "-c:a", "libmp3lame",
                            "-b:a", "96k", str(target)], check=True)
            duration = probe(target)
            # Leave a quarter-second lead-in and a tenth-second tail before the cut.
            if duration > 7.65:
                raise SystemExit(scene["id"] + " exceeds its speech window; shorten its text.")
            clips.append({"id": scene["id"], "duration_seconds": duration,
                          "bytes": target.stat().st_size,
                          "sha256": hashlib.sha256(target.read_bytes()).hexdigest()})
            print(scene["id"] + ": " + str(round(duration, 3)) + " seconds")

    # Original sine-pad score: C / Am / F / G, with smooth chord boundaries.
    # No external recording, stochastic source or licensed sample is used.
    rate = script["sample_rate"]
    frequencies = ((130.8128, 164.8138, 195.9977), (110, 130.8128, 164.8138),
                   (87.3071, 110, 130.8128), (97.9989, 123.4708, 146.8324))
    samples = array("h")
    for index in range(48 * rate):
        time = index / rate
        chord_time = time % 12
        chord = frequencies[int(time // 12)]
        envelope = min(1, chord_time / 1.5, (12 - chord_time) / 1.5)
        value = sum(math.sin(2 * math.pi * hz * time)
                    + 0.15 * math.sin(2 * math.pi * hz * 2 * time) for hz in chord)
        samples.append(round(value * envelope * 1800))
    if sys.byteorder != "little":
        samples.byteswap()
    bed = public / "background.wav"
    with wave.open(str(bed), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(rate)
        output.writeframes(samples.tobytes())
    (ROOT / "audio.json").write_text(json.dumps({
        "clips": clips,
        "music": {"path": "background.wav", "duration_seconds": 48,
                  "bytes": bed.stat().st_size,
                  "sha256": hashlib.sha256(bed.read_bytes()).hexdigest(),
                  "source": "Original deterministic sine-pad score generated by prepare-audio.py"},
        "normalization": "Polly clips: FFmpeg loudnorm I=-18, TP=-2, LRA=7; music gain 0.20 during narration, 0.32 between clips."
    }, indent=2) + "\n")


if __name__ == "__main__":
    main()
