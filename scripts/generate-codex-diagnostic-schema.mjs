#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DIAGNOSTIC_COLUMNS, diagnosticSchemaSql, diagnosticBackfillSql } from "../dashboard/server/codexDiagnosticSchema.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const marker = "-- BEGIN GENERATED CODEX DIAGNOSTIC V1";
const end = "-- END GENERATED CODEX DIAGNOSTIC V1";
const replicated = diagnosticSchemaSql({ replicated: true });
const literal = value => "'" + value.replaceAll("'", "\\'") + "'";
const columns = DIAGNOSTIC_COLUMNS.map(([column, dataType]) =>
  [literal('codex_diagnostic_events_v1'), literal(column), literal(dataType)]);
const guard = `SELECT throwIf(
  (SELECT count() FROM system.columns WHERE database='claude_code'
    AND (table,name,type) IN (${columns.map(tuple => "(" + tuple.join(",") + ")").join(",\n    ")})) != ${columns.length},
  'Codex diagnostic schema columns differ; repair before recording migration 008');`;
const ledger = checksum => `${guard}

INSERT INTO claude_code.schema_migrations (version,name,checksum) SELECT 8, '008-codex-diagnostic-states', '${checksum}'
WHERE (SELECT count() FROM claude_code.schema_migrations WHERE version=4) > 0
AND (SELECT count() FROM claude_code.schema_migrations WHERE version=8) = 0;`;
const migration = checksum => `-- Generated by scripts/generate-codex-diagnostic-schema.mjs.
-- Additive schema only. Verify replicas and bounded backfill before setting CODEX_DIAGNOSTIC_READ_FROM.
SELECT throwIf((SELECT count() FROM claude_code.schema_migrations WHERE version=4)=0,
  'Migration 008 requires migration ledger 004');

${replicated}

${ledger(checksum)}\n`;
// Match the numbered migration convention: exclude the complete ledger INSERT
// line, including its checksum, but include the remaining guards and predicates.
const checksum = createHash("sha256").update(migration("").split("\n")
  .filter(line => !line.includes("INSERT INTO claude_code.schema_migrations")).join("\n")).digest("hex");
function output(path, content) {
  let original;
  try { original = readFileSync(root + path, "utf8"); } catch { original = null; }
  if (original === content) return;
  if (check) throw new Error("Generated Codex diagnostic schema differs: " + path);
  writeFileSync(root + path, content);
}
for (const [path, ddl] of [
  ["clickhouse-schema.sql", diagnosticSchemaSql()],
  ["infra/files/clickhouse-schema-replicated.sql", replicated],
]) {
  const original = readFileSync(root + path, "utf8");
  const block = `${marker}\n-- Generated by scripts/generate-codex-diagnostic-schema.mjs; data readiness is separate.\n${ddl}\n\n${ledger(checksum)}\n${end}\n`;
  output(path, original.includes(marker)
    ? original.slice(0, original.indexOf(marker)) + block + original.slice(original.indexOf(end) + end.length).replace(/^\n/, "")
    : original.trimEnd() + "\n\n" + block);
}
output("clickhouse-migration-008.sql", migration(checksum));
output("clickhouse-backfill-008.sql", `-- Generated by scripts/generate-codex-diagnostic-schema.mjs.
-- Run once per shard with bound backfillFrom/backfillTo; at most one day per invocation.
-- Repeatable, including overlaps with live MVs. Does not activate the read path.
${diagnosticBackfillSql()}\n`);
