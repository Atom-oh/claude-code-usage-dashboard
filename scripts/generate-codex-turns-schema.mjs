#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { TURNS_ROLLUP_COLUMNS, TURNS_ROLLUP_TABLE, codexTurnsSchemaSql, codexTurnsBackfillSql, codexTurnsVerifySql } from "../dashboard/server/codexTurnsSchema.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const marker = "-- BEGIN GENERATED CODEX TURNS V1";
const end = "-- END GENERATED CODEX TURNS V1";
const replicated = codexTurnsSchemaSql({ replicated: true });
const literal = value => "'" + value.replaceAll("'", "\\'") + "'";
const columns = TURNS_ROLLUP_COLUMNS.map(([column, dataType]) =>
  [literal(TURNS_ROLLUP_TABLE), literal(column), literal(dataType)]);
const guard = `SELECT throwIf(
  (SELECT count() FROM system.columns WHERE database='claude_code'
    AND (table,name,type) IN (${columns.map(tuple => "(" + tuple.join(",") + ")").join(",\n    ")})) != ${columns.length},
  'Codex turns schema columns differ; repair before recording migration 012');`;
const ledger = checksum => `${guard}

INSERT INTO claude_code.schema_migrations (version,name,checksum) SELECT 12, '012-codex-turns', '${checksum}'
WHERE (SELECT count() FROM claude_code.schema_migrations WHERE version=4) > 0
AND (SELECT count() FROM claude_code.schema_migrations WHERE version=12) = 0;`;
const migration = checksum => `-- Generated by scripts/generate-codex-turns-schema.mjs.
-- Additive schema only. Verify replicas and bounded backfill before setting CODEX_TURNS_READ_FROM.
SELECT throwIf((SELECT count() FROM claude_code.schema_migrations WHERE version=4)=0,
  'Migration 012 requires migration ledger 004');
SELECT throwIf((SELECT count() FROM system.tables WHERE database='claude_code' AND name='otel_traces')=0,
  'Migration 012 requires otel_traces from migration 002');

${replicated}

${ledger(checksum)}\n`;
// Match the numbered migration convention: exclude the complete ledger INSERT
// line, including its checksum, but include the remaining guards and predicates.
const checksum = createHash("sha256").update(migration("").split("\n")
  .filter(line => !line.includes("INSERT INTO claude_code.schema_migrations")).join("\n")).digest("hex");
function output(path, content) {
  let original;
  try { original = readFileSync(root + path, "utf8"); } catch { original = null; }
  if (original === content) return;
  if (check) throw new Error("Generated Codex turns schema differs: " + path);
  writeFileSync(root + path, content);
}
for (const [path, ddl] of [
  ["clickhouse-schema.sql", codexTurnsSchemaSql()],
  ["infra/files/clickhouse-schema-replicated.sql", replicated],
]) {
  const original = readFileSync(root + path, "utf8");
  const block = `${marker}\n-- Generated by scripts/generate-codex-turns-schema.mjs; data readiness is separate.\n${ddl}\n\n${ledger(checksum)}\n${end}\n`;
  output(path, original.includes(marker)
    ? original.slice(0, original.indexOf(marker)) + block + original.slice(original.indexOf(end) + end.length).replace(/^\n/, "")
    : original.trimEnd() + "\n\n" + block);
}
output("clickhouse-migration-012.sql", migration(checksum));
output("clickhouse-backfill-012.sql", `-- Generated by scripts/generate-codex-turns-schema.mjs.
-- Run once per shard with bound backfillFrom/backfillTo; at most one day per invocation.
-- Repeatable, including overlaps with the live MV. Does not activate the read path.
${codexTurnsBackfillSql()}\n`);
output("clickhouse-verify-012.sql", `-- Generated by scripts/generate-codex-turns-schema.mjs.
-- Read-only activation check: bind hour-aligned UTC verifyFrom/verifyTo. Raw spans in
-- [verifyFrom - 1h, verifyTo + 24h) must be backfilled and retained. One row per turn: any
-- differs = 1 blocks CODEX_TURNS_READ_FROM; clipped = 1 rows are counted, not compared.
${codexTurnsVerifySql()}\n`);
