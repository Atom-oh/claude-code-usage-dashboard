#!/usr/bin/env python3
"""Compile the replicated schema's metadata contract without customer or AWS data."""

import argparse
import hashlib
from pathlib import Path
import re
from schema_lifecycle_fixture import SchemaFixture


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "infra/files/clickhouse-schema-replicated.sql"
CONTRACT = ROOT / "infra/files/clickhouse-schema-contract.sql"

# Codec/order differences do not change the named exporter input or materialized values.
COLUMNS_QUERY = """SELECT table,
  hex(SHA256(toString(arraySort(groupArray(tuple(name, type, default_kind, default_expression)))))) AS signature
FROM system.columns WHERE database = 'claude_code' GROUP BY table ORDER BY table"""
TABLES_QUERY = """SELECT name, engine, partition_key, sorting_key, primary_key,
  extract(replaceAll(create_table_query, '\\n', ' '), ' TTL (.*?)(?: SETTINGS |$)') AS ttl,
  as_select, storage_policy
FROM system.tables WHERE database = 'claude_code' ORDER BY name"""


def literal(value):
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def array(rows):
    return "[\n  " + ",\n  ".join(
        "(" + ", ".join(literal(value) for value in row) + ")" for row in rows
    ) + "\n]"


def compile_contract():
    source = SCHEMA.read_text()
    with SchemaFixture(ROOT) as fixture:
        fixture.query(source, mutations_sync=2, distributed_ddl_task_timeout=60)
        tables = fixture.rows(TABLES_QUERY)
        columns = fixture.rows(COLUMNS_QUERY)
        ledger = fixture.rows(
            "SELECT version, name, checksum FROM claude_code.schema_migrations ORDER BY version"
        )
        paths = fixture.rows(
            "SELECT table, replaceOne(zookeeper_path, "
            "concat('/clickhouse/tables/', (SELECT substitution FROM system.macros WHERE macro = 'shard'), '/'), "
            "'/clickhouse/tables/{shard}/') AS path "
            "FROM system.replicas WHERE database = 'claude_code' ORDER BY table"
        )
    if [row["version"] for row in ledger] != [2, 3, 4, 5, 6, 7]:
        raise RuntimeError("Reference schema did not record every required migration.")
    names = [row["name"] for row in tables]
    declared = re.findall(
        r"CREATE (?:TABLE|MATERIALIZED VIEW) IF NOT EXISTS claude_code\.([a-z0-9_]+)", source
    )
    if sorted(declared) != names:
        raise RuntimeError("Reference objects do not match the schema's declared objects.")
    owned = "[" + ", ".join(literal(name) for name in names) + "]"
    table_rows = [
        tuple(row[name] for name in ("name", "engine", "partition_key", "sorting_key", "primary_key", "ttl", "as_select"))
        for row in tables
    ]
    policy_rows = [(row["name"], row["storage_policy"]) for row in tables]
    path_rows = [(row["table"], row["path"]) for row in paths]
    return f"""-- schema-source-sha256: {hashlib.sha256(SCHEMA.read_bytes()).hexdigest()}
-- Generated by scripts/build-schema-contract.py on the declared ClickHouse 24.8 image.
-- Named columns/types/default expressions, engines/keys/TTL/view routing, policies, paths and ledger.
-- This is read-only compatibility evidence, not historical backfill or recovery verification.
SELECT throwIf(
  (SELECT arraySort(groupArray(tuple(name, engine, partition_key, sorting_key, primary_key,
    extract(replaceAll(create_table_query, '\\n', ' '), ' TTL (.*?)(?: SETTINGS |$)'), as_select)))
   FROM system.tables WHERE database = 'claude_code' AND name IN {owned})
  != {array(table_rows)}, 'SCHEMA_COMPATIBILITY: tables, keys, TTL or materialized view differ; follow the schema migration runbook');

SELECT throwIf(
  (SELECT arraySort(groupArray(tuple(table, signature))) FROM
    (SELECT table, hex(SHA256(toString(arraySort(groupArray(tuple(name, type, default_kind, default_expression)))))) AS signature
     FROM system.columns WHERE database = 'claude_code' AND table IN {owned} GROUP BY table))
  != {array([(row["table"], row["signature"]) for row in columns])},
  'SCHEMA_COMPATIBILITY: column types or materialized expressions differ; follow the schema migration runbook');

-- Migration 003 deliberately permits the established DELETE-only hourly table on default storage.
SELECT throwIf(
  (SELECT arraySort(groupArray(tuple(name,
    if(name = 'otel_metrics_sum_hourly' AND storage_policy = 'default', 'hot_cold', storage_policy))))
   FROM system.tables WHERE database = 'claude_code' AND name IN {owned})
  != {array(policy_rows)}, 'SCHEMA_COMPATIBILITY: storage policies differ');

SELECT throwIf(
  (SELECT arraySort(groupArray(tuple(table, replaceOne(zookeeper_path,
     concat('/clickhouse/tables/', (SELECT substitution FROM system.macros WHERE macro = 'shard'), '/'),
     '/clickhouse/tables/{{shard}}/'))))
   FROM system.replicas WHERE database = 'claude_code' AND table IN {owned})
  != {array(path_rows)}, 'SCHEMA_COMPATIBILITY: replicated paths differ; do not attach or rebuild implicitly');

SELECT throwIf(
  (SELECT arraySort(groupArray(tuple(version, name, checksum))) FROM claude_code.schema_migrations)
  != {array([(row["version"], row["name"], row["checksum"]) for row in ledger])},
  'SCHEMA_COMPATIBILITY: migration ledger differs; do not fabricate completion records');

SELECT throwIf(
  (SELECT count() FROM system.tables WHERE database = 'claude_code' AND name = 'otel_metrics_sum_hourly_mv'
    AND position(replaceAll(create_table_query, '`', ''), 'TO claude_code.otel_metrics_sum_hourly ') > 0) != 1,
  'SCHEMA_COMPATIBILITY: hourly materialized view target differs');

-- The creator is installation-specific; require explicit definer security so
-- insert-only collectors never need permission to read raw logs.
SELECT throwIf(
  (SELECT count() FROM system.tables WHERE database = 'claude_code'
    AND name IN ('codex_cost_events_v1_mv', 'codex_cost_scope_v1_mv')
    AND position(create_table_query, ' SQL SECURITY DEFINER') > 0
    AND position(create_table_query, 'DEFINER = ') > 0) != 2,
  'SCHEMA_COMPATIBILITY: Codex cost views require explicit definer security');
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed contract differs.")
    arguments = parser.parse_args()
    content = compile_contract()
    if arguments.check:
        if not CONTRACT.exists() or CONTRACT.read_text() != content:
            raise SystemExit("Schema contract is stale; regenerate and review the schema and migration changes.")
        print("Schema contract matches the declared schema on ClickHouse 24.8.")
    else:
        CONTRACT.write_text(content)
        print("Generated " + str(CONTRACT.relative_to(ROOT)))
