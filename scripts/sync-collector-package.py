#!/usr/bin/env python3
"""Generate package policies from tracked canonical sources; --check detects drift."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "dashboard/collector/generated"


def policies():
    source = (ROOT / "collector-config.yaml").read_text()
    processors = source.split("\nprocessors:\n", 1)[1].split("\nexporters:\n", 1)[0]
    service = source.split("\nservice:\n", 1)[1]
    exporters = source.split("\nexporters:\n", 1)[1].split("\nservice:\n", 1)[0]
    # Existing resource attribution always wins at both collection hops.
    processors = processors.replace("value: ${env:EXPERIMENT_GROUP}\n        action: upsert",
                                    'value: ${env:EXPERIMENT_GROUP:-unknown}\n        action: insert')
    processors = processors.replace("${env:CODEX_ENABLED:-false}", "${env:CODEX_ENABLED:-true}")
    processors += "\n" + (ROOT / "dashboard/collector/privacy-processors.yaml").read_text()
    service = service.replace("filter/traces_claude, resource, batch",
                              "filter/traces_claude, filter/claude_trace_content, transform/claude_trace_content, resource, batch")
    service = service.replace("filter/logs_claude, transform/scrub_logs, resource, batch",
                              "filter/logs_claude, transform/scrub_logs, transform/device_log_content, resource, batch")
    service = service.replace("transform/codex_logs, batch", "transform/codex_logs, transform/device_log_content, batch")
    header = "# Generated by scripts/sync-collector-package.py; edit the canonical policy.\n"
    local_extensions = """extensions:
  file_storage:
    directory: ${env:OTELCOL_QUEUE_DIR}
    create_directory: true
  bearertokenauth:
    filename: ${env:CCDASH_TOKEN_FILE}
  health_check:
    endpoint: 127.0.0.1:13133
receivers:
  otlp:
    protocols:
      grpc:
        endpoint: 127.0.0.1:4317
        include_metadata: true
      http:
        endpoint: 127.0.0.1:4318
        include_metadata: true
"""
    local_exporters = """exporters:
  otlp_http:
    endpoint: ${env:CCDASH_INGEST_ENDPOINT}
    compression: none
    timeout: 15s
    auth:
      authenticator: bearertokenauth
    retry_on_failure:
      enabled: true
      initial_interval: 5s
      max_interval: 30s
      max_elapsed_time: 0
    sending_queue:
      enabled: true
      num_consumers: 2
      queue_size: 1000
      storage: file_storage
"""
    local_service = re.sub(r"exporters: \[clickhouse(?:/codex)?\]", "exporters: [otlp_http]", service)
    local_service = local_service.replace("extensions: [file_storage]",
                                          "extensions: [file_storage, bearertokenauth, health_check]")
    local_processors = processors.replace('value: ${env:EXPERIMENT_GROUP:-unknown}\n        action: insert',
                                          'value: ${env:EXPERIMENT_GROUP:-unknown}\n        action: insert\n'
                                          '      - key: user.email\n'
                                          '        value: "${env:CODEX_DEFAULT_USER_EMAIL:-}"\n        action: insert')
    local = header + local_extensions + "processors:\n" + local_processors + "\n" + local_exporters
    local += "service:\n" + local_service
    central_extensions = """extensions:
  bearertokenauth:
    filename: /var/run/ccdash-ingest/token
  health_check:
    endpoint: 0.0.0.0:13133
receivers:
  otlp:
    protocols:
      http:
        endpoint: 0.0.0.0:4318
        max_request_body_size: 2097152
        auth:
          authenticator: bearertokenauth
"""
    # Transport headers exist only at the device hop. Valid inferred resource
    # provenance must survive proxying and mixed batches at the central hop.
    central_processors = re.sub(r"\n  resource/codex_transport:.*?(?=\n  transform/codex_resource:)",
                                "\n", processors, flags=re.S)
    # The current exporter discovers EventName but does not distinguish the
    # existing MATERIALIZED column from an ordinary column. Preserve its exact
    # LogAttributes['event.name'] contract when explicitly inserting it.
    central_processors += """
  transform/clickhouse_event_name:
    error_mode: propagate
    log_statements:
      - context: log
        statements:
          - set(event_name, "")
          - set(event_name, String(attributes["event.name"])) where attributes["event.name"] != nil
"""
    central_service = service.replace("resource/codex_transport, ", "")
    central_service = central_service.replace("transform/device_log_content,",
                                              "transform/device_log_content, transform/clickhouse_event_name,")
    central_service = central_service.replace("extensions: [file_storage]",
                                              "extensions: [bearertokenauth, health_check]")
    exporters = exporters.replace("password: ${env:CH_PASSWORD}",
                                  "password: ${file:/var/run/ccdash-clickhouse/CH_PASSWORD}")
    # The private ClusterIP exposes native ClickHouse, not the external TLS NLB.
    exporters = exporters.replace("?secure=true", "?secure=false")
    exporters = exporters.replace("      storage: file_storage\n", "")
    # ClickHouse 24.8's async path rejects an explicitly inserted MATERIALIZED
    # EventName even with insert_allow_materialized_columns. Native synchronous
    # inserts accept it; the transform above supplies the exact existing value.
    # The SQL fixture covers this with the pinned Collector and unchanged DDL.
    exporters = exporters.replace("    create_schema: false\n",
                                  '    create_schema: false\n    async_insert: false\n    connection_params:\n'
                                  '      insert_allow_materialized_columns: "1"\n')
    central = header + central_extensions + "processors:\n" + central_processors
    central += "\nexporters:\n" + exporters + "\nservice:\n" + central_service
    # Keep generated files concise; comments and source policy explanations live
    # with their canonical owners. Quoted OTTL strings are not YAML comments.
    clean = lambda text: "\n".join(line for line in text.splitlines()
                                  if not line.lstrip().startswith("#")) + "\n"
    return {"local.yaml": header + clean(local), "central.yaml": header + clean(central),
            "configure-client-telemetry.py": (ROOT / "scripts/configure-client-telemetry.py").read_text()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for name, content in policies().items():
        path = OUTPUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if mismatches:
        parser.exit(1, "Collector generated sources drifted: " + ", ".join(mismatches) + "\n")


if __name__ == "__main__":
    main()
